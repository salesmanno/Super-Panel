        <script>
        document.querySelectorAll('.toggle-payment-gateway').forEach(button => {
            button.addEventListener('click', function() {
                const gatewayId = this.dataset.gatewayId;
                const gatewayName = this.dataset.gatewayName;
                const isActive = this.dataset.isActive === '1';
                const newStatus = !isActive;
                
                // Validering: Kontant kan kun deaktiveres hvis en annen er aktivert
                if (gatewayName === 'cash' && isActive) {
                    const otherActive = Array.from(document.querySelectorAll('.toggle-payment-gateway'))
                        .some(btn => btn.dataset.gatewayName !== 'cash' && btn.dataset.isActive === '1');
                    
                    if (!otherActive) {
                        alert('Kontant kan kun deaktiveres når minst én annen betalingsmetode er aktivert.');
                        return;
                    }
                }
                
                fetch('/api/toggle_payment_gateway.php', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ 
                        gateway_id: gatewayId,
                        is_active: newStatus
                    })
                })
                .then(response => response.json())
                .then(data => {
                    if (data.success) {
                        location.reload();
                    } else {
                        alert('Feil: ' + (data.error || 'Kunne ikke oppdatere betalingsmetode'));
                    }
                })
                .catch(error => {
                    alert('En feil oppstod ved oppdatering av betalingsmetode');
                });
            });
        });
        </script>
