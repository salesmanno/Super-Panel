                <td>${tx.supplier || 'Ukjent'}</td>
                <td class="text-end">${formatCurrency(tx.amount)}</td>
            </tr>
        `).join('');
    } else {
        tbody.innerHTML = '<tr><td colspan="5" class="text-center text-muted py-3">Ingen utgifter funnet for valgt periode</td></tr>';
    }
}

function formatCurrency(amount) {
    return new Intl.NumberFormat('nb-NO', {
        style: 'decimal',
        minimumFractionDigits: 2,
        maximumFractionDigits: 2
    }).format(amount) + ' NOK';
}

function formatDate(dateString) {
    const date = new Date(dateString);
    return new Intl.DateTimeFormat('nb-NO', {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit'
    }).format(date);
}

function translateModule(moduleName) {
    const translations = {
        'sales': 'Salg',
        'events': 'Arrangement',
        'membership': 'Medlemskap',
        'rental': 'Utleie',
        'reservations': 'Reservasjoner'
    };
    return translations[moduleName] || moduleName;
}

