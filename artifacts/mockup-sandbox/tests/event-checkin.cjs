  await settle();
  const search = document.querySelector('[aria-label="Søk blant deltakere"]');
  value(search, "zzznobody");
  await settle();
  check(document.querySelector(".uc-empty"), "Search empty state");
  value(search, "9900000000002");
  await settle();
  check(document.querySelectorAll(".uc-attendee").length === 1 && row("Marius"), "Barcode lookup");
  search.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true }));
  await settle();
  check(row("Marius").querySelector(".uc-checked-status"), "Barcode checks in prepaid attendee");
  check(!document.querySelector(".uc-ledger"), "Prepaid has no new ledger");
